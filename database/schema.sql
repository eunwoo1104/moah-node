CREATE DATABASE IF NOT EXISTS moah_node DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;

USE moah_node;

CREATE TABLE IF NOT EXISTS user(
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    permission INT UNSIGNED DEFAULT 0
);

CREATE TABLE IF NOT EXISTS media(
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    dir VARCHAR(40),
    created_at DATETIME,
    uploader INT UNSIGNED,
    FOREIGN KEY (uploader) REFERENCES user(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tag(
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(32) UNIQUE,
    description VARCHAR(32) DEFAULT NULL
);

CREATE TABLE IF NOT EXISTS tag_map(
    media_id INT UNSIGNED,
    tag_id INT UNSIGNED,
    PRIMARY KEY (media_id, tag_id),
    FOREIGN KEY (media_id) REFERENCES media(id) ON DELETE CASCADE,
    FOREIGN KEY (tag_id) REFERENCES tag(id) ON DELETE CASCADE
);
