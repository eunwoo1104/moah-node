CREATE DATABASE IF NOT EXISTS moah_node DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;

USE moah_node;

CREATE TABLE IF NOT EXISTS user(
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    permission INT UNSIGNED DEFAULT 0
);

CREATE TABLE IF NOT EXISTS media(
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    dir VARCHAR(40),
    created_at DATETIME,
    uploader INT UNSIGNED,
    FOREIGN KEY (uploader) REFERENCES user(id) ON DELETE CASCADE
);
