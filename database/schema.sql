CREATE DATABASE IF NOT EXISTS moah_node DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;

USE moah_node;

CREATE TABLE IF NOT EXISTS core(
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    auth VARCHAR(256) NOT NULL
);

CREATE TABLE IF NOT EXISTS media(
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    dir VARCHAR(40),
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    uploaded_from INT UNSIGNED,
    FOREIGN KEY (uploaded_from) REFERENCES core(id) ON DELETE NO ACTION
);
